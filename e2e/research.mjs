// Browser E2E for the research lifecycle (Phase III) against the running demo stack.
// Providers here: Tavily = LOCAL CONTRACT FAKE (tests/fixtures/fake_tavily.py), Bifrost = REAL gateway with a LOCAL FAKE upstream model.
// This is NOT live-provider evidence. Usage: node e2e/research.mjs   (env: UI, PASSCODE, API)
import { createRequire } from "node:module";
import fs from "node:fs";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const UI = process.env.UI || "http://127.0.0.1:5173";
const API = process.env.API || "http://127.0.0.1:8080";
const PASS = process.env.PASSCODE || "demo-pass";
const SHOTS = process.env.SHOTS || "/var/tmp/shots";
fs.mkdirSync(SHOTS, { recursive: true });
const steps = [];
const ok = (name, cond, detail = "") => { steps.push({ name, status: cond ? "PASS" : "FAIL", detail }); console.log(`${cond ? "PASS" : "FAIL"}  ${name} ${detail}`); if (!cond) throw new Error(`step failed: ${name}`); };
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 2200 } });
let navs = 0;
page.on("framenavigated", (f) => { if (f === page.mainFrame()) navs++; });
const txt = async (sel) => (await page.locator(sel).first().innerText().catch(() => "")) || "";
try {
  await page.goto(`${UI}/#workspace`);
  await page.waitForSelector(".ws");
  const base = navs;
  await page.fill('input[name="pc"]', PASS); await page.click('button:has-text("Sign in")');
  await page.waitForSelector("text=signed in as");
  const before = (await page.locator(".ws-head h1").first().innerText().catch(() => "")) || "";
  await page.click('button:has-text("Reset demo data")'); await page.waitForSelector(".ws-msg.ok");
  await page.click('button:has-text("Trigger NetworkPolicy incident")');
  await page.waitForFunction((old) => { const h = document.querySelector(".ws-head h1"); return h && h.textContent !== old; }, before, { timeout: 60000 });
  await page.waitForFunction(() => document.querySelectorAll(".ws-table tbody tr").length >= 8, null, { timeout: 90000 }); // change + 6 logs + alert
  ok("incident with source events appears live", true);
  await page.waitForSelector(".rs-NOT_STARTED");
  ok("research status starts NOT_STARTED and answer NEVER_RESEARCHED", (await txt(".bs-NEVER")).includes("NEVER_RESEARCHED"));

  await page.click('button:has-text("Research this incident")');
  await page.waitForSelector(".rs-COMPLETED", { timeout: 60000 });
  ok("research run COMPLETED from the UI", true);
  ok("budget and credits are displayed from the backend", /\d+ \/ \d+ used/.test(await txt('[aria-label="research budget"]')) && /reported/.test(await txt('[aria-label="research budget"]')));
  const attempts = await page.locator("details:has-text('Research activity') tbody tr").count();
  ok("every external attempt is listed with its Tavily request id", attempts >= 5 && (await page.locator("details:has-text('Research activity') tbody tr td.mono").allInnerTexts()).some((t) => /[0-9a-f]{8}-/.test(t)), `attempts=${attempts}`);

  await page.click('button:has-text("Synthesize with Bifrost")');
  await page.waitForSelector(".badge.org-BIFROST_MODEL", { timeout: 60000 });
  ok("brief generated by Bifrost with a real gateway request id", /Bifrost request [^\s]+/.test(await txt("#research")));
  ok("source-established, inference and hypothesis findings are labelled apart", (await page.locator(".kd-SOURCE_ESTABLISHED").count()) > 0 && (await page.locator(".kd-MODEL_INFERENCE").count()) > 0 && (await page.locator(".kd-HYPOTHESIS").count()) > 0);
  const research = await txt("#research");
  ok("citations carry domain and publication date (or 'date unknown')", /kubernetes\.io · (Tue|Wed|Mon|date unknown)/.test(research));
  ok("fabricated citation was demoted (validation message shown)", /fabricated source ids rejected/.test(research));
  ok("evidence strength is a server-derived category", /evidence strength: (STRONG|MODERATE|WEAK|INSUFFICIENT)/.test(research));
  ok("version 1 is FRESH", (await txt(".bs-FRESH")).includes("v1"));
  await page.screenshot({ path: `${SHOTS}/r1-brief.png`, fullPage: true });

  // new relevant evidence arrives through the real ingestion boundary and Pathway
  const inc = (await page.locator(".ws-head h1").first().innerText()).trim();
  const view = await (await fetch(`${API}/api/ns/incidents/${inc}`, { headers: { "x-beacon-passcode": PASS } })).json();
  const run = view.correlations[view.correlations.length - 1].run_id;
  const r = await fetch(`${API}/ingest/app-logs`, { method: "POST", headers: { "content-type": "application/json", authorization: "Bearer alert-token" }, body: JSON.stringify({ records: [{ id: `late-${Date.now()}`, ts: new Date().toISOString(), namespace: "demo", app: "demo-api", target_app: "demo-db", line: "ERROR database unreachable at demo-db:6379: timed out", source_mode: "DEMO_SIMULATOR", run_id: run }] }) });
  ok("new evidence accepted at the ingestion boundary", r.status === 200);
  await page.waitForSelector('[role="alert"]:has-text("STALE ANSWER")', { timeout: 60000 });
  ok("answer turns STALE live, naming the rule and the new event", /NEW_RELEVANT_EVENT/.test(await txt('#research [role="alert"]')));
  ok("original explanation is retained while stale", (await page.locator(".badge.org-BIFROST_MODEL").count()) > 0);
  await page.screenshot({ path: `${SHOTS}/r2-stale.png`, fullPage: true });

  const before2 = await page.locator("details:has-text('Research activity') tbody tr").count();
  await page.click('button:has-text("Run follow-up searches")');
  await page.waitForFunction((n) => document.querySelectorAll("details tbody tr").length > n, before2, { timeout: 60000 });
  ok("follow-up searches ran only after the explicit click", true);
  ok("the unsafe follow-up (internal name) never reached the provider", !(await (await fetch("http://127.0.0.1:9400/__seen")).text()).toLowerCase().includes("demo-db"));

  await page.click('button:has-text("Refresh explanation")');
  await page.waitForFunction(() => document.querySelectorAll("button.ghost").length >= 2 && /v2 · FRESH|v2 · STALE/.test(document.body.innerText), null, { timeout: 60000 });
  const body = await txt("#research");
  ok("a new version appears; the earlier version is retained and SUPERSEDED", /v1 · SUPERSEDED/.test(body) && /v2 · (FRESH|STALE)/.test(body));
  await page.click('button:has-text("v1 · SUPERSEDED")');
  ok("the older version remains viewable", /version 1/.test(await txt("#research")));
  ok("no page reload happened", navs === base);
  await page.screenshot({ path: `${SHOTS}/r3-versions.png`, fullPage: true });
} finally {
  fs.writeFileSync(`${SHOTS}/research-journey.json`, JSON.stringify({ steps, providers: { tavily: "LOCAL_CONTRACT_FAKE", bifrost: "REAL_GATEWAY_FAKE_UPSTREAM" } }, null, 2));
  await browser.close();
}
